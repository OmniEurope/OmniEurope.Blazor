    H1 = 1,

    /// <summary>An <c>h2</c>.</summary>
    H2,

    /// <summary>An <c>h3</c>.</summary>
    H3,

    /// <summary>An <c>h4</c>.</summary>
    H4,

    /// <summary>An <c>h5</c>.</summary>
    H5,

    /// <summary>An <c>h6</c>.</summary>
    H6
}
